# build_imdb_csv.R
#
# Builds the cleaned, deduplicated IMDb labeled-review CSV used throughout
# the CIND860 SHAP project, from the raw Stanford "aclImdb" review files.
#
# Input : data/IMDB Movies/aclImdb/{train,test}/{pos,neg}/*.txt
# Output: data/IMDB Movies/imdb_labeled_clean.csv
#
# Pipeline:
#   1. Build file metadata (split/label/id/rating) for all labeled reviews.
#   2. Read raw text and clean it (strip HTML, lowercase, strip punctuation
#      except apostrophes, collapse whitespace).
#   3. Remove exact cross-split duplicate reviews (drop the train-side copy).
#   4. Write text_raw, text_clean, label, split, rating to CSV.
#
# NOTE: this script only removes exact cross-split duplicates. It does not
# perform near-duplicate removal (8-word-opening blocking + 3-gram shingle
# Jaccard similarity > 0.5), so it reproduces 49,877 rows, not the 49,874-row
# imdb_labeled_clean.csv on disk (which also had 3 near-duplicate train-side
# rows removed). See project memory for that additional step if the CSV
# needs to be regenerated byte-for-byte.
#
# Verified 2026-10-16: 50,000 total labeled files -> 123 exact train-side
# dupes dropped -> 49,877 rows (train: 12,407 neg / 12,470 pos; test: 12,500
# neg / 12,500 pos).

library(tidyverse)
library(fs)

data_dir <- "data/IMDB Movies/aclImdb"
output_csv <- "data/IMDB Movies/imdb_labeled_clean.csv"

# --- 1. Build file metadata for labeled reviews (train/test x pos/neg) -----
list_review_files <- function(split, label) {
  dir_path <- path(data_dir, split, label)
  tibble(
    path  = dir_ls(dir_path, glob = "*.txt"),
    split = split,
    label = label
  )
}

meta <- bind_rows(
  list_review_files("train", "pos"),
  list_review_files("train", "neg"),
  list_review_files("test",  "pos"),
  list_review_files("test",  "neg")
) |>
  mutate(
    file   = path_file(path),
    id     = as.integer(str_extract(file, "^\\d+")),
    rating = as.integer(str_extract(file, "(?<=_)\\d+(?=\\.txt$)"))
  )

# --- 2. Read raw text and clean it ------------------------------------------
clean_review <- function(text) {
  text |>
    str_replace_all("<br\\s*/?>", " ") |>
    str_replace_all("<[^>]+>", " ") |>
    str_to_lower() |>
    str_replace_all("[^a-z0-9'\\s]", " ") |>
    str_replace_all("\\s+", " ") |>
    str_trim()
}

labeled <- meta |>
  mutate(text_raw = map_chr(path, read_file)) |>
  mutate(
    text_clean = clean_review(text_raw),
    n_words    = str_count(text_clean, "\\S+")
  )

# --- 3. Remove exact cross-split duplicates (drop train-side copy) ---------
dup_text <- labeled |>
  count(text_raw, name = "n_copies") |>
  filter(n_copies > 1) |>
  pull(text_raw)

exact_dupe_rows <- labeled |>
  filter(text_raw %in% dup_text) |>
  group_by(text_raw) |>
  filter(n() > 1, n_distinct(split) > 1) |>
  ungroup()

to_drop_exact <- exact_dupe_rows |> filter(split == "train")

labeled <- labeled |> anti_join(to_drop_exact, by = c("path"))

message("After exact-duplicate removal: ", nrow(labeled), " rows (",
        nrow(to_drop_exact), " train-side exact dupes dropped)")

# --- 4. Write the cleaned, deduplicated CSV --------------------------------
labeled |>
  select(text_raw, text_clean, label, split, rating) |>
  write_csv(output_csv)

message("Wrote ", nrow(labeled), " rows to ", output_csv)
